-- 结构定义：11张表、主外键、检查约束、ALTER、条件唯一索引和派生视图。 / Schema:11 tables, keys, checks, ALTER, conditional unique indexes and derived views.
-- Oracle 19c+. Create in a dedicated EMPTY schema. No destructive cleanup here.

CREATE TABLE MEMBER_TYPE (
  member_type_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  type_name VARCHAR2(40) NOT NULL,
  loan_limit NUMBER(3) NOT NULL,
  loan_days NUMBER(3) NOT NULL,
  max_renewals NUMBER(2) NOT NULL,
  CONSTRAINT pk_member_type PRIMARY KEY (member_type_id),
  CONSTRAINT ck_member_type_1 CHECK (loan_limit BETWEEN 1 AND 999),
  CONSTRAINT ck_member_type_2 CHECK (loan_days BETWEEN 1 AND 365),
  CONSTRAINT ck_member_type_3 CHECK (max_renewals BETWEEN 0 AND 99)
);

CREATE TABLE LIB_MEMBER (
  member_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  matric_no VARCHAR2(20) NOT NULL,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(254) NOT NULL,
  member_type_id NUMBER(10) NOT NULL,
  expires_on DATE NOT NULL,
  status VARCHAR2(10) NOT NULL,
  CONSTRAINT pk_lib_member PRIMARY KEY (member_id),
  CONSTRAINT uq_lib_member_matric_no UNIQUE (matric_no),
  CONSTRAINT uq_lib_member_email UNIQUE (email),
  CONSTRAINT fk_lib_member_member_type_id FOREIGN KEY (member_type_id) REFERENCES MEMBER_TYPE(member_type_id),
  CONSTRAINT ck_lib_member_1 CHECK (status IN ('ACTIVE','SUSPENDED'))
);

CREATE TABLE STAFF (
  staff_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  staff_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(254) NOT NULL,
  CONSTRAINT pk_staff PRIMARY KEY (staff_id),
  CONSTRAINT uq_staff_email UNIQUE (email)
);

CREATE TABLE PUBLISHER (
  publisher_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  publisher_name VARCHAR2(120) NOT NULL,
  CONSTRAINT pk_publisher PRIMARY KEY (publisher_id)
);

CREATE TABLE BOOK_TITLE (
  title_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  isbn VARCHAR2(13),
  title_name VARCHAR2(200) NOT NULL,
  publisher_id NUMBER(10),
  publication_year NUMBER(4),
  CONSTRAINT pk_book_title PRIMARY KEY (title_id),
  CONSTRAINT uq_book_title_isbn UNIQUE (isbn),
  CONSTRAINT fk_book_title_publisher_id FOREIGN KEY (publisher_id) REFERENCES PUBLISHER(publisher_id),
  CONSTRAINT ck_book_title_1 CHECK (isbn IS NULL OR REGEXP_LIKE(isbn, '^[0-9]{13}$')),
  CONSTRAINT ck_book_title_2 CHECK (publication_year BETWEEN 1450 AND 2100)
);

CREATE TABLE AUTHOR (
  author_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  author_name VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_author PRIMARY KEY (author_id)
);

CREATE TABLE TITLE_AUTHOR (
  title_id NUMBER(10) NOT NULL,
  author_id NUMBER(10) NOT NULL,
  CONSTRAINT pk_title_author PRIMARY KEY (title_id, author_id),
  CONSTRAINT fk_title_author_title_id FOREIGN KEY (title_id) REFERENCES BOOK_TITLE(title_id),
  CONSTRAINT fk_title_author_author_id FOREIGN KEY (author_id) REFERENCES AUTHOR(author_id)
);

CREATE TABLE BOOK_COPY (
  copy_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  barcode VARCHAR2(30) NOT NULL,
  title_id NUMBER(10) NOT NULL,
  shelf_code VARCHAR2(30) NOT NULL,
  copy_status VARCHAR2(10) NOT NULL,
  CONSTRAINT pk_book_copy PRIMARY KEY (copy_id),
  CONSTRAINT uq_book_copy_barcode UNIQUE (barcode),
  CONSTRAINT fk_book_copy_title_id FOREIGN KEY (title_id) REFERENCES BOOK_TITLE(title_id),
  CONSTRAINT ck_book_copy_1 CHECK (copy_status IN ('AVAILABLE','REPAIR','LOST'))
);

CREATE TABLE LOAN (
  loan_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  copy_id NUMBER(10) NOT NULL,
  member_id NUMBER(10) NOT NULL,
  staff_id NUMBER(10) NOT NULL,
  borrowed_on DATE NOT NULL,
  due_on DATE NOT NULL,
  returned_on DATE,
  CONSTRAINT pk_loan PRIMARY KEY (loan_id),
  CONSTRAINT fk_loan_copy_id FOREIGN KEY (copy_id) REFERENCES BOOK_COPY(copy_id),
  CONSTRAINT fk_loan_member_id FOREIGN KEY (member_id) REFERENCES LIB_MEMBER(member_id),
  CONSTRAINT fk_loan_staff_id FOREIGN KEY (staff_id) REFERENCES STAFF(staff_id),
  CONSTRAINT ck_loan_1 CHECK (due_on > borrowed_on),
  CONSTRAINT ck_loan_2 CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);

CREATE TABLE RENEWAL (
  renewal_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  loan_id NUMBER(10) NOT NULL,
  staff_id NUMBER(10) NOT NULL,
  renewed_on DATE NOT NULL,
  previous_due_on DATE NOT NULL,
  new_due_on DATE NOT NULL,
  CONSTRAINT pk_renewal PRIMARY KEY (renewal_id),
  CONSTRAINT fk_renewal_loan_id FOREIGN KEY (loan_id) REFERENCES LOAN(loan_id),
  CONSTRAINT fk_renewal_staff_id FOREIGN KEY (staff_id) REFERENCES STAFF(staff_id),
  CONSTRAINT ck_renewal_1 CHECK (new_due_on > previous_due_on)
);

CREATE TABLE RESERVATION (
  reservation_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
  title_id NUMBER(10) NOT NULL,
  member_id NUMBER(10) NOT NULL,
  reserved_on DATE NOT NULL,
  reservation_status VARCHAR2(10) NOT NULL,
  closed_on DATE,
  CONSTRAINT pk_reservation PRIMARY KEY (reservation_id),
  CONSTRAINT fk_reservation_title_id FOREIGN KEY (title_id) REFERENCES BOOK_TITLE(title_id),
  CONSTRAINT fk_reservation_member_id FOREIGN KEY (member_id) REFERENCES LIB_MEMBER(member_id),
  CONSTRAINT ck_reservation_1 CHECK (reservation_status IN ('ACTIVE','FULFILLED','CANCELLED')),
  CONSTRAINT ck_reservation_2 CHECK ((reservation_status = 'ACTIVE' AND closed_on IS NULL) OR (reservation_status IN ('FULFILLED','CANCELLED') AND closed_on IS NOT NULL AND closed_on >= reserved_on))
);


-- ALTER is intentionally demonstrated separately from CREATE.
ALTER TABLE MEMBER_TYPE ADD CONSTRAINT uq_member_type_name UNIQUE (type_name);
CREATE UNIQUE INDEX uq_loan_open_copy ON LOAN
  (CASE WHEN returned_on IS NULL THEN copy_id END);
CREATE UNIQUE INDEX uq_reservation_active ON RESERVATION
  (CASE WHEN reservation_status = 'ACTIVE' THEN member_id END,
   CASE WHEN reservation_status = 'ACTIVE' THEN title_id END);
CREATE INDEX ix_member_type ON LIB_MEMBER(member_type_id);
CREATE INDEX ix_title_publisher ON BOOK_TITLE(publisher_id);
CREATE INDEX ix_title_author_author ON TITLE_AUTHOR(author_id);
CREATE INDEX ix_copy_title ON BOOK_COPY(title_id);
CREATE INDEX ix_loan_member ON LOAN(member_id, returned_on);
CREATE INDEX ix_loan_staff ON LOAN(staff_id);
CREATE INDEX ix_renewal_loan ON RENEWAL(loan_id);
CREATE INDEX ix_renewal_staff ON RENEWAL(staff_id);
CREATE INDEX ix_reservation_queue ON RESERVATION(title_id, reservation_status, reserved_on, reservation_id);
CREATE INDEX ix_reservation_member ON RESERVATION(member_id);
CREATE OR REPLACE VIEW v_copy_availability AS
 SELECT c.copy_id, c.barcode, c.title_id, c.shelf_code, c.copy_status,
 CASE WHEN c.copy_status = 'AVAILABLE' AND NOT EXISTS
   (SELECT 1 FROM LOAN l WHERE l.copy_id=c.copy_id AND l.returned_on IS NULL)
 THEN 'YES' ELSE 'NO' END AS can_lend
 FROM BOOK_COPY c;
CREATE OR REPLACE VIEW v_active_loans AS
 SELECT l.loan_id, m.matric_no, m.full_name, c.barcode, t.title_name,
 l.borrowed_on, l.due_on,
 GREATEST(TRUNC(SYSDATE)-TRUNC(l.due_on),0) AS days_overdue
 FROM LOAN l JOIN LIB_MEMBER m ON m.member_id=l.member_id
 JOIN BOOK_COPY c ON c.copy_id=l.copy_id
 JOIN BOOK_TITLE t ON t.title_id=c.title_id
 WHERE l.returned_on IS NULL;
